// 曲: ノーツの位置でベルが鳴る、やさしいポップ
const PROG = ['C4+E4+G4', 'G3+B3+D4', 'A3+C4+E4', 'F3+A3+C4'];
const ROOT = ['C2', 'G1', 'A1', 'F1'];
const LANE_NOTE = ['C5', 'E5', 'G5', 'C6'];
export const TUTORIAL_DEF = {
  id: 'tutorial',
  title: 'Tutorial',
  artist: 'MUSIC LiDAR',
  genre: 'TUTORIAL',
  bpm: TUT_BPM,
  color: '#5ef2ff',
  levels: { easy: 1, normal: 1, hard: 1 },
  compose(s) {
    for (let b = 0; b < 29; b++) {
      s.pad(b * 4, PROG[b % 4].split('+'), 4, 0.35);
      s.bass(b * 4, ROOT[b % 4], 1.5, 0.8); s.bass(b * 4 + 2, ROOT[b % 4], 1.5, 0.6);
      if (b >= 2) { s.kick(b * 4, 0.8); s.kick(b * 4 + 2, 0.7); s.hat(b * 4 + 1, 0.4); s.hat(b * 4 + 3, 0.4); }
      if (b >= 6) { s.snare(b * 4 + 1, 0.5); s.snare(b * 4 + 3, 0.5); }
    }
    for (const [b, lane, e] of STEPS) {
      if (e) s.lead(b, LANE_NOTE[lane], e - b, 0.6);
      else s.bell(b, LANE_NOTE[lane], 0.5, 0.9);
    }
    s.crash(112, 0.6); s.pad(112, ['C4', 'E4', 'G4', 'C5'], 4, 0.6); s.bell(112, 'C6', 3);
  },
};
